def read_text(path):
    try:
        with open(path, encoding="utf-8", newline="") as f:
            return f.read()
    except OSError:
        return None


def stale_pages(generated):
    out = []
    for fn in sorted(os.listdir(ROOT)):
        if re.fullmatch(r"project-\d+\.html", fn) and fn not in generated:
            body = read_text(os.path.join(ROOT, fn)) or ""
            if MARKER in body[:300]:
                out.append(fn)
    return out


def cmd_build(check=False):
    try:
        home, projects = load_all()
        pages = build_pages(home, projects) if home is not None and not errors else {}
    except TemplateError as e:
        err("template", str(e))
        pages = {}
    for w in warnings:
        print("warning:", w)
    if errors:
        print("\nBuild stopped, nothing was written. Fix these:")
        for e in errors:
            print("  error:", e)
        return 1

    changed, same = [], []
    for fn, body in sorted(pages.items()):
        (same if read_text(os.path.join(ROOT, fn)) == body else changed).append(fn)
    stale = stale_pages(pages)
    drafts = [p["where"] for p in projects if p["draft"]]

    if check:
        for fn in changed:
            print("would change:", fn)
        for fn in stale:
            print("would delete:", fn)
        print("up to date" if not (changed or stale) else "out of date: run python build.py")
        return 1 if (changed or stale) else 0

    for fn in changed:
        path = os.path.join(ROOT, fn)
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8", newline="\n") as f:
            f.write(pages[fn])
        os.replace(tmp, path)
    for fn in stale:
        os.remove(os.path.join(ROOT, fn))
    print("Built %d page(s): %d written, %d unchanged%s." % (
        len(pages), len(changed), len(same), (", %d removed" % len(stale)) if stale else ""))
    for fn in changed:
        print("  wrote", fn)
    for fn in stale:
        print("  removed", fn, "(project no longer exists or is a draft)")
    for w in drafts:
        print("  skipped draft:", w)
    return 0


