def bookmarks(live, active):
    items = [{"href": "index.html", "color": "green", "label": "Home", "active": active == "home"}]
    for p in live:
        items.append({"href": p["file"], "color": p["color"], "label": "Project " + p["num"], "active": active == p["slug"]})
    items.append({"href": "index.html#contact", "color": "blue", "label": "Contact", "active": False})
    return items


def build_pages(home, projects):
    live = [p for p in projects if not p["draft"]]
    pages = {}

    # ---- home ----
    lines = [{"id": "intro", "color": "green", "label": "Intro"}]
    lines += [{"id": p["slug"], "color": p["color"], "label": "Project-" + p["num"]} for p in live]
    lines.append({"id": "contact", "color": "blue", "label": "Contact"})
    cards = []
    for i, p in enumerate(live):
        cards.append({"file": p["file"], "color": p["color"], "slug": p["slug"], "cover": p["cover"],
                      "cover_alt": p["cover_alt"], "code": p["code"], "title": p["card_title"],
                      "summary": p["summary"], "tags": p["tags"], "last": i == len(live) - 1})
    hctx = dict(home)
    hctx["projects"] = cards
    content = render("home.html", hctx)
    pages["index.html"] = render("base.html", {
        "title": home["title"], "description": home["description"],
        "bookmarks": bookmarks(live, "home"), "paper_class": "s-home", "page_color": "green",
        "paper_lines": lines, "blanks": [{}] * max(0, HOME_BLANK_TARGET - len(lines)),
        "content": content, "footer": home["footer"]})

    # ---- projects ----
    for i, p in enumerate(live):
        sections = [("heading", "Heading", "green")]
        numbered = {}
        n = 0
        for key, sid, label, color, present in (
                ("info", "information", "Information", "brown", bool(p["info"])),
                ("photos", "photos", "Photos", "orange", bool(p["photos"])),
                ("research", "research", "Research", "purple", bool(p["research"])),
                ("results", "results", "Results", "red", bool(p["results"]))):
            if present:
                n += 1
                numbered["n_" + key] = "%02d" % n
                sections.append((sid, label, color))
        nxt = live[i + 1] if i + 1 < len(live) else None
        pctx = dict(p)
        pctx.update(numbered)
        pctx["next_href"] = nxt["file"] if nxt else "index.html#projects"
        pctx["next_label"] = "Next project" if nxt else "All projects"
        for k, v in p["equations"].items():
            pctx["eq_" + k] = v
        for k in ("n_info", "n_photos", "n_research", "n_results"):
            pctx.setdefault(k, "")
        content = render("project.html", pctx)
        plines = [{"id": s[0], "color": s[2], "label": s[1]} for s in sections]
        pages[p["file"]] = render("base.html", {
            "title": "%s | %s" % (p["code"], home["hero_name"]), "description": "",
            "bookmarks": bookmarks(live, p["slug"]), "paper_class": "s-project", "page_color": p["color"],
            "paper_lines": plines, "blanks": [{}] * max(0, PROJECT_BLANK_TARGET - len(plines)),
            "content": content, "footer": home["project_footer"]})
    return pages


