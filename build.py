def err(where, msg):
    errors.append("%s: %s" % (where, msg))


def warn(where, msg):
    warnings.append("%s: %s" % (where, msg))


# ----------------------------------------------------------------------------
# tiny template engine
#   {{name}}  escaped value      {{{name}}}  raw HTML
#   {{#if x}}..{{/if}}   {{#unless x}}..{{/unless}}   {{#each list}}..{{/each}}
#   names can be dotted (handle.x); inside {{#each}} the item's fields are in scope,
#   and {{.}} is the item itself for lists of plain strings.
#   A line holding only a block tag is removed, so templates stay readable.
# ----------------------------------------------------------------------------
TOKEN = re.compile(
    r"\{\{\{\s*([\w.]+)(?:\|([ \t]*))?\s*\}\}\}"
    r"|\{\{\s*(?:#(if|unless|each)\s+([\w.]+)|/(if|unless|each)|([\w.]+))\s*\}\}")
BLOCK_LINE = re.compile(r"^[ \t]*(\{\{\s*(?:#(?:if|unless|each)\s+[\w.]+|/(?:if|unless|each))\s*\}\})[ \t]*(?:\n|\Z)", re.M)
RAW_LINE = re.compile(r"^([ \t]*)\{\{\{\s*([\w.]+)\s*\}\}\}[ \t]*$", re.M)


class TemplateError(Exception):
    pass


def parse(src, name):
    src = BLOCK_LINE.sub(r"\1", src)
    src = RAW_LINE.sub(lambda m: "{{{%s|%s}}}" % (m.group(2), m.group(1)), src)
    root, stack, opened, pos = [], [], [], 0
    cur = root
    for m in TOKEN.finditer(src):
        if m.start() > pos:
            cur.append(("text", src[pos:m.start()]))
        pos = m.end()
        raw, indent, kw, kname, close, var = m.groups()
        if raw:
            cur.append(("var", raw, True, indent or ""))
        elif var:
            cur.append(("var", var, False, ""))
        elif kw:
            node = (kw, kname, [])
            cur.append(node)
            stack.append(cur)
            opened.append(kw)
            cur = node[2]
        else:
            if not opened or opened[-1] != close:
                line = src.count("\n", 0, m.start()) + 1
                raise TemplateError("%s: unexpected {{/%s}} near line %d" % (name, close, line))
            opened.pop()
            cur = stack.pop()
    if opened:
        raise TemplateError("%s: {{#%s}} is never closed" % (name, opened[-1]))
    cur.append(("text", src[pos:]))
    return root


_MISSING = object()


def lookup(scopes, name):
    parts = name.split(".") if name != "." else ["."]
    for scope in reversed(scopes):
        if isinstance(scope, dict) and parts[0] in scope:
            val = scope[parts[0]]
            for p in parts[1:]:
                if isinstance(val, dict) and p in val:
                    val = val[p]
                else:
                    return _MISSING
            return val
    return _MISSING


def truthy(v):
    return v is not _MISSING and bool(v)


def emit(nodes, scopes, tname):
    out = []
    for n in nodes:
        kind = n[0]
        if kind == "text":
            out.append(n[1])
        elif kind == "var":
            v = lookup(scopes, n[1])
            if v is _MISSING:
                raise TemplateError("%s: unknown placeholder {{%s}}" % (tname, n[1]))
            s = "" if v is None else str(v)
            if not n[2]:
                s = html.escape(s, quote=True)
            elif n[3]:
                s = "\n".join(n[3] + line if line else line for line in s.split("\n"))
            out.append(s)
        elif kind == "if":
            if truthy(lookup(scopes, n[1])):
                out.append(emit(n[2], scopes, tname))
        elif kind == "unless":
            if not truthy(lookup(scopes, n[1])):
                out.append(emit(n[2], scopes, tname))
        elif kind == "each":
            items = lookup(scopes, n[1])
            if items is _MISSING:
                raise TemplateError("%s: unknown list {{#each %s}}" % (tname, n[1]))
            for item in items or []:
                scope = item if isinstance(item, dict) else {".": item}
                out.append(emit(n[2], scopes + [scope], tname))
    return "".join(out)


def render(template_name, ctx):
    path = os.path.join(TEMPLATES, template_name)
    try:
        with open(path, encoding="utf-8") as f:
            src = f.read()
    except OSError as e:
        raise TemplateError("cannot read templates/%s: %s" % (template_name, e.strerror))
    return emit(parse(src, "templates/" + template_name), [ctx], "templates/" + template_name)


