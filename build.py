def rel(path):
    return os.path.relpath(path, ROOT).replace(os.sep, "/")


def load_json(path):
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except OSError as e:
        err(rel(path), "cannot read (%s)" % e.strerror)
        return None
    except json.JSONDecodeError as e:
        err(rel(path), "invalid JSON at line %d, column %d: %s" % (e.lineno, e.colno, e.msg))
        return None
    if not isinstance(data, dict):
        err(rel(path), "top level must be a JSON object { ... }")
        return None
    return data


def text(d, key, where, required=False, default=""):
    """Read a string field; report an error if it is missing (required) or not a string."""
    v = d.get(key)
    if v is None or v == "":
        if required:
            err(where, 'missing required field "%s"' % key)
        return default
    if not isinstance(v, str):
        err(where, '"%s" must be text' % key)
        return default
    return v.strip()


def color_of(d, key, where, default):
    v = d.get(key)
    if v is None:
        return default
    if v not in COLORS:
        err(where, '"%s" is "%s" but must be one of: %s' % (key, v, ", ".join(COLORS)))
        return default
    return v


def check_image(path_value, where, what):
    """Validate an image path (relative to the repo root, under assets/). Returns the path or ''."""
    if not isinstance(path_value, str) or not path_value:
        err(where, "%s needs an image path like assets/project-01/01.webp" % what)
        return ""
    p = path_value.strip()
    if not re.fullmatch(r"assets/[A-Za-z0-9_./-]+", p) or ".." in p.split("/"):
        err(where, '%s "%s": use a path under assets/ with only letters, digits, - _ . /' % (what, p))
        return ""
    if not p.lower().endswith(IMAGE_EXT):
        err(where, '%s "%s": unsupported file type (use %s)' % (what, p, ", ".join(IMAGE_EXT)))
        return ""
    full = os.path.join(ROOT, p)
    if not os.path.isfile(full):
        err(where, '%s "%s": file not found' % (what, p))
        return ""
    if os.path.getsize(full) > BIG_IMAGE:
        warn(where, '%s "%s" is %d KB; run "python build.py images" to shrink it' % (what, p, os.path.getsize(full) // 1024))
    return p


def eq_overrides(d, defaults, where):
    eq = dict(defaults)
    given = d.get("equations")
    if given is None:
        return eq
    if not isinstance(given, dict):
        err(where, '"equations" must be an object')
        return eq
    for k, v in given.items():
        if k not in defaults:
            err(where, 'unknown equation slot "%s" (allowed: %s)' % (k, ", ".join(defaults)))
        elif not isinstance(v, str):
            err(where, 'equation "%s" must be text ("" hides it)' % k)
        else:
            eq[k] = v
    return eq


def prepare_home(d):
    where = "content/home.json"
    meta = d.get("meta") if isinstance(d.get("meta"), dict) else {}
    hero = d.get("hero") if isinstance(d.get("hero"), dict) else {}
    proj = d.get("projects") if isinstance(d.get("projects"), dict) else {}
    contact = d.get("contact") if isinstance(d.get("contact"), dict) else {}
    for key in ("meta", "hero", "projects", "contact"):
        if not isinstance(d.get(key), dict):
            err(where, 'missing section "%s"' % key)

    h = {
        "title": text(meta, "title", where + " meta", True),
        "description": text(meta, "description", where + " meta"),
        "hero_label": text(hero, "label", where + " hero"),
        "hero_name": text(hero, "name", where + " hero", True),
        "hero_tagline": text(hero, "tagline", where + " hero"),
        "hero_intro": text(hero, "intro", where + " hero"),
        "hero_button": text(hero, "button", where + " hero", default="See projects"),
        "figure_caption": text(hero, "figureCaption", where + " hero"),
        "projects_label": text(proj, "label", where + " projects", default="Projects"),
        "projects_title": text(proj, "title", where + " projects", default="Selected work"),
        "contact_intro": text(contact, "intro", where + " contact"),
        "footer": text(d, "footer", where, default=""),
        "project_footer": text(d, "projectFooter", where, default=""),
    }
    rows = []
    for i, r in enumerate(contact.get("rows") or [], 1):
        w = "%s contact.rows[%d]" % (where, i)
        if not isinstance(r, dict):
            err(w, "must be an object with label, text, href")
            continue
        href = text(r, "href", w, True)
        if href and not re.match(r"^(https?://|mailto:|tel:|/|#)", href):
            err(w, 'href "%s" must start with https://, http://, mailto:, tel:, / or #' % href)
            href = ""
        rows.append({"label": text(r, "label", w, True), "text": text(r, "text", w, True), "href": href})
    h["contact_rows"] = rows
    for k, v in eq_overrides(d, EQ_HOME, where).items():
        h["eq_" + k] = v
    return h


def prepare_project(path, num, index):
    where = rel(path)
    d = load_json(path)
    if d is None:
        return None
    if d.get("draft") is True:
        return {"draft": True, "num": num, "where": where}
    p = {"draft": False, "where": where, "num": num}
    p["slug"] = "project-" + num
    p["file"] = p["slug"] + ".html"
    p["code"] = "PRJ-" + num
    p["color"] = color_of(d, "color", where, PROJECT_COLORS[index % len(PROJECT_COLORS)])
    p["title"] = text(d, "title", where, True)
    p["card_title"] = text(d, "cardTitle", where, default=p["title"])   # name on the home-page card
    p["tagline"] = text(d, "tagline", where)
    p["summary"] = text(d, "summary", where, True)
    p["kind"] = text(d, "kind", where, default="Technical project")

    tags = d.get("tags") or []
    if not isinstance(tags, list) or not all(isinstance(t, str) for t in tags):
        err(where, '"tags" must be a list of text, e.g. ["CAD", "ESP32"]')
        tags = []
    p["tags"] = [t.strip() for t in tags if t.strip()]

    cover = d.get("cover")
    p["cover"] = check_image(cover, where, "cover") if cover else ""
    p["cover_alt"] = text(d, "coverAlt", where, default=p["title"])

    info = []
    for i, r in enumerate(d.get("info") or [], 1):
        w = "%s info[%d]" % (where, i)
        if not isinstance(r, dict):
            err(w, "must be an object with label and value")
            continue
        info.append({"label": text(r, "label", w, True), "value": text(r, "value", w, True)})
    p["info"] = info

    photos = []
    for i, ph in enumerate(d.get("photos") or [], 1):
        w = "%s photos[%d]" % (where, i)
        if not isinstance(ph, dict):
            err(w, "must be an object with src (or placeholder)")
            continue
        item = {"src": "", "alt": "", "placeholder": "", "handle": None}
        if ph.get("src"):
            item["src"] = check_image(ph.get("src"), w, "src")
            item["alt"] = text(ph, "alt", w)
            if not item["alt"]:
                warn(w, 'no "alt" text (describe the photo for screen readers)')
        elif ph.get("placeholder"):
            item["placeholder"] = text(ph, "placeholder", w, True)
        else:
            err(w, 'needs "src" (an image path) or "placeholder" (text)')
        hd = ph.get("handle")
        if hd is not None:
            if not isinstance(hd, dict):
                err(w, '"handle" must be an object')
            else:
                hw = w + " handle"
                name, htext, value = text(hd, "name", hw, True), text(hd, "text", hw), text(hd, "value", hw, True)
                col = color_of(hd, "color", hw, "green")
                tip = text(hd, "tipColor", hw, default=TIP_COLORS[col])
                if not re.fullmatch(r"#[0-9a-fA-F]{6}", tip):
                    err(hw, '"tipColor" must look like #3fb37a')
                    tip = TIP_COLORS[col]
                pos = {}
                for axis in ("x", "y"):
                    v = text(hd, axis, hw, True)
                    if v and not re.fullmatch(r"\d{1,3}(\.\d{1,2})?%", v):
                        err(hw, '"%s" must be a percentage like "76%%"' % axis)
                        v = "50%"
                    pos[axis] = v or "50%"
                item["handle"] = {"name": name, "text": htext, "value": value, "color": col, "tip_color": tip,
                                  "x": pos["x"], "y": pos["y"], "aria": " ".join(s for s in (name, htext, value) if s)}
        photos.append(item)
    p["photos"] = photos

    research = []
    for i, b in enumerate(d.get("research") or [], 1):
        w = "%s research[%d]" % (where, i)
        if not isinstance(b, dict):
            err(w, 'must be an object with "type"')
            continue
        t = b.get("type")
        blk = {"is_text": False, "is_formula": False, "is_image": False, "text": "", "src": "", "alt": ""}
        if t in ("text", "formula"):
            blk["is_" + t] = True
            blk["text"] = text(b, "text", w, True)
        elif t == "image":
            blk["is_image"] = True
            blk["src"] = check_image(b.get("src"), w, "src")
            blk["alt"] = text(b, "alt", w)
            if not blk["alt"]:
                warn(w, 'no "alt" text (describe the image for screen readers)')
        else:
            err(w, '"type" must be text, formula or image (got %r)' % (t,))
            continue
        research.append(blk)
    p["research"] = research

    res = d.get("results")
    p["results"] = None
    if res is not None:
        if not isinstance(res, dict):
            err(where, '"results" must be an object with stats and text')
        else:
            stats = []
            for i, s in enumerate(res.get("stats") or [], 1):
                w = "%s results.stats[%d]" % (where, i)
                if not isinstance(s, dict):
                    err(w, "must be an object with value and label")
                    continue
                stats.append({"value": text(s, "value", w, True), "label": text(s, "label", w, True)})
            rtext = text(res, "text", where + " results")
            if stats or rtext:
                p["results"] = {"stats": stats, "text": rtext}

    p["equations"] = eq_overrides(d, EQ_PROJECT, where)
    return p


def load_all():
    home_data = load_json(os.path.join(CONTENT, "home.json"))
    home = prepare_home(home_data) if home_data is not None else None

    files = []
    if os.path.isdir(CONTENT):
        for fn in os.listdir(CONTENT):
            m = re.fullmatch(r"project-(\d+)\.json", fn)
            if m:
                files.append((int(m.group(1)), m.group(1).zfill(2), fn))
            elif fn.endswith(".json") and fn != "home.json":
                warn("content/" + fn, 'ignored (page files are named project-01.json, project-02.json, ...)')
    files.sort()
    projects, index = [], 0
    for _, num, fn in files:
        p = prepare_project(os.path.join(CONTENT, fn), num, index)
        if p is None:
            continue
        if not p["draft"]:
            index += 1
        projects.append(p)
    return home, projects


